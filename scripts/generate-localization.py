#!/usr/bin/env python3
"""Generate the dependency-free runtime catalog; no network or user storage access."""
from pathlib import Path
import json, sys
root = Path(__file__).resolve().parents[1]
catalog = json.loads((root / 'Resources/Localization/catalog.json').read_text())
rows = []
for key, translations in sorted(catalog.items()):
    assert set(translations) == {'en', 'ru', 'uz-Latn'}, key
    languages = []
    for locale, forms in sorted(translations.items()):
        if isinstance(forms, str): forms = {'other': forms}
        assert 'other' in forms and all(forms.values()) and all(v != 'TODO' for v in forms.values()), key
        form_items = ', '.join(json.dumps(k) + ': ' + json.dumps(v, ensure_ascii=False) for k, v in sorted(forms.items()))
        languages.append(json.dumps(locale) + ': [' + form_items + ']')
    rows.append('        ' + json.dumps(key) + ': [' + ', '.join(languages) + ']')
source = '// Generated by scripts/generate-localization.py. Edit Resources/Localization/catalog.json.\nimport Foundation\n\nextension L10n {\n    static let catalog: [String: [String: [String: String]]] = [\n' + ',\n'.join(rows) + '\n    ]\n}\n'
target = root / 'Sources/CodexSwoopCore/LocalizationCatalog.swift'
if '--check' in sys.argv:
    assert target.read_text() == source, 'Regenerate localization catalog'
else:
    target.write_text(source)
print(f'PASS localization generation: {len(catalog)} keys, EN/RU/UZ-Latn')
